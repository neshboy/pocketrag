import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { extractPdfFile } from "../src/extract/pdf.js";

const FIXTURE_PATH = fileURLToPath(new URL("./fixtures/sample.pdf", import.meta.url));

describe("extractPdfFile", () => {
  it("extracts real text from a real PDF (generated by pdf-lib, see scripts/generate-pdf-fixture.mjs)", async () => {
    const text = await extractPdfFile(FIXTURE_PATH);

    expect(text.length).toBeGreaterThan(0);
    // Exact phrases embedded in the fixture's content stream.
    expect(text).toContain("PocketRAG Fixture Document");
    expect(text).toContain("PocketRAG is a local retrieval augmented generation pipeline.");
    expect(text).toContain("The quick brown fox jumps over the lazy dog near the riverbank.");
    expect(text).toContain("Okapi BM25 ranking over a SQLite-backed inverted index.");
  });

  it("produces text that is itself chunkable and tokenizable like any other extracted document", async () => {
    const { chunkText } = await import("../src/chunker.js");
    const text = await extractPdfFile(FIXTURE_PATH);
    const chunks = chunkText(text, { chunkSize: 15, overlap: 5 });

    expect(chunks.length).toBeGreaterThan(0);
    expect(chunks.some((c) => c.text.includes("PocketRAG"))).toBe(true);
  });
});
